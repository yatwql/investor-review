"""收益率口径标签 —— 提示词里「同一个百分比是哪一种收益率」的唯一声明点。

背景：事实校验实测单轮修正 10 处收益率数值（如 `561910` 写成 11.1%、实际 -34.9%），
且高度集中在同一批品种上——模型把**持仓收益率**（自买入，成本口径，未年化）与
**区间收益率**（回看窗口内）或**累计收益率**（自成立）混为一谈。修正器只保证数值
被改对，句意里的口径仍可能是错的。

因此提示词中的收益率一律**带口径标签**，不再出现裸「收益率」：
- 持仓行/组合：`:data:`LABEL_POSITION` / :data:`LABEL_PORTFOLIO`
- 区间对比：`:data:`LABEL_INTERVAL`
- 另附 :data:`CALIBER_NOTE` 一次性说明「三者不可混用」

`PROMPT_SCHEMA_VERSION` 是「提示词文本版本」：标签/表头等**静态文本**改动不会改变
行情与持仓数据，因而不会改变结构化指纹——把版本号并入模块指纹（见
`llm.fingerprint.build_llm_fingerprint`）才能让旧缓存失效，避免复用按旧口径生成的
结论。改动提示词文案时**必须**同步递增该版本（一次性换键、旧缓存自动重算，属预期）。
"""

